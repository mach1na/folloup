esp_err_t Init()
{
    LoadContext ctx;
    const esp_err_t err = storage_service::RunWithMountedFilesystem(LoadRegistryOnMountedFilesystem, &ctx);

    std::vector<Topic> topics;
    bool needs_seed_write = false;
    const bool storage_available = err == ESP_OK && ctx.storage_available;
    if (storage_available) {
        if (ctx.loaded_from_file) {
            topics = std::move(ctx.topics);
        } else {
            topics = BuildDefaultTopics();
            needs_seed_write = true;
        }
    }

    {
        std::lock_guard<std::mutex> lock(s_mutex);
        s_snapshot.initialized = true;
        s_snapshot.storage_available = storage_available;
        s_snapshot.topics = topics;
    }

    if (needs_seed_write && !PersistRegistry(topics)) {
        ESP_LOGW(kTag, "Failed to persist seeded default topics");
    }

    ESP_LOGI(kTag, "Init: storage_available=%d topic_count=%d", storage_available ? 1 : 0,
             static_cast<int>(topics.size()));
    return err;
}

void SetEventHandler(EventHandler handler, void* context)
{
    std::lock_guard<std::mutex> lock(s_mutex);
    s_event_handler = handler;
    s_event_context = context;
}

Snapshot GetSnapshot()
{
    std::lock_guard<std::mutex> lock(s_mutex);
    return s_snapshot;
}

std::string Create(const std::string& name)
{
    const std::string trimmed = TrimWhitespace(name);
    if (trimmed.empty()) {
        return {};
    }

    std::string new_id;
    std::vector<Topic> topics_copy;
    {
        std::lock_guard<std::mutex> lock(s_mutex);
        if (!s_snapshot.storage_available) {
            return {};
        }
        new_id = GenerateNextId(s_snapshot.topics);
        Topic topic;
        topic.id = new_id;
        topic.name = trimmed;
        topic.created_unix_seconds = static_cast<int64_t>(std::time(nullptr));
        s_snapshot.topics.push_back(std::move(topic));
        topics_copy = s_snapshot.topics;
    }

    if (!PersistRegistry(topics_copy)) {
        std::lock_guard<std::mutex> lock(s_mutex);
        s_snapshot.topics.erase(
            std::remove_if(s_snapshot.topics.begin(), s_snapshot.topics.end(),
                           [&](const Topic& topic) { return topic.id == new_id; }),
            s_snapshot.topics.end());
        return {};
    }

    NotifyHandler();
    return new_id;
}

bool Rename(const std::string& id, const std::string& name)
{
    const std::string trimmed = TrimWhitespace(name);
    if (id.empty() || trimmed.empty()) {
        return false;
    }

    std::string previous_name;
    std::vector<Topic> topics_copy;
    {
        std::lock_guard<std::mutex> lock(s_mutex);
        if (!s_snapshot.storage_available) {
            return false;
        }
        auto it = std::find_if(s_snapshot.topics.begin(), s_snapshot.topics.end(),
                               [&](const Topic& topic) { return topic.id == id; });
        if (it == s_snapshot.topics.end()) {
            return false;
        }
        previous_name = it->name;
        it->name = trimmed;
        topics_copy = s_snapshot.topics;
    }

    if (!PersistRegistry(topics_copy)) {
        std::lock_guard<std::mutex> lock(s_mutex);
        auto it = std::find_if(s_snapshot.topics.begin(), s_snapshot.topics.end(),
                               [&](const Topic& topic) { return topic.id == id; });
        if (it != s_snapshot.topics.end()) {
            it->name = previous_name;
        }
        return false;
    }

    NotifyHandler();
    return true;
}

bool Delete(const std::string& id)
{
    if (id.empty()) {
        return false;
    }

    Topic removed;
    std::vector<Topic> topics_copy;
    {
        std::lock_guard<std::mutex> lock(s_mutex);
        if (!s_snapshot.storage_available) {
            return false;
        }
        auto it = std::find_if(s_snapshot.topics.begin(), s_snapshot.topics.end(),
                               [&](const Topic& topic) { return topic.id == id; });
        if (it == s_snapshot.topics.end()) {
            return false;
        }
        removed = *it;
        s_snapshot.topics.erase(it);
        topics_copy = s_snapshot.topics;
    }

    if (!PersistRegistry(topics_copy)) {
        std::lock_guard<std::mutex> lock(s_mutex);
        s_snapshot.topics.push_back(removed);
        return false;
    }

    NotifyHandler();
    return true;
}

